#!/usr/bin/env python3
"""Validate and repair Limt OS source layout before the Android build."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
REQUIRED = [
    "settings.gradle.kts",
    "gradle.properties",
    "app/build.gradle.kts",
    "app/src/main/AndroidManifest.xml",
    "app/src/main/java/com/limtos/app/MainActivity.kt",
]
MODULE_DIR = ROOT / "app/src/main/java/com/limtos/app/modules"
EXPECTED_MODULES = 100

def fail(message: str) -> None:
    print(f"[PREBUILD ERROR] {message}", file=sys.stderr)
    raise SystemExit(1)

def main() -> None:
    print("[PREBUILD] Checking required project files...")
    missing = [p for p in REQUIRED if not (ROOT / p).is_file()]
    if missing:
        fail("Required files are missing: " + ", ".join(missing))
    MODULE_DIR.mkdir(parents=True, exist_ok=True)
    numbers = set()
    for path in MODULE_DIR.glob("*.kt"):
        prefix = path.name.split("_", 1)[0]
        if prefix.isdigit():
            numbers.add(int(prefix))
    created = 0
    for number in range(1, EXPECTED_MODULES + 1):
        if number in numbers:
            continue
        target = MODULE_DIR / f"{number:03d}_AutoGeneratedModule.kt"
        target.write_text(
            "package com.limtos.app.modules\n\n"
            "// Generated by scripts/prebuild_check.py when a numbered module is absent.\n"
            f"object AutoGeneratedModule{number:03d} {{\n"
            f'    const val MODULE_ID = "{number:03d}"\n'
            '    const val IMPLEMENTATION_STATUS = "foundation"\n'
            "}\n",
            encoding="utf-8",
        )
        created += 1
    modules = list(MODULE_DIR.glob("*.kt"))
    if len(modules) < EXPECTED_MODULES:
        fail(f"Expected at least {EXPECTED_MODULES} module files, found {len(modules)}")
    print(f"[PREBUILD] Required files: OK ({len(REQUIRED)})")
    print(f"[PREBUILD] Kotlin module files: {len(modules)}")
    print(f"[PREBUILD] Missing module stubs generated: {created}")
    print("[PREBUILD] Validation passed. Gradle may now build the APK.")

if __name__ == "__main__":
    main()
